"""udev rules for the hardware this app opens, generated from the app's own device
tables so they never drift from the code (``python -m wdgwars_uploader.linux.udev``).

* USB radios opened through libusb (RTL-SDR, HackRF, monitor-mode adapters
  without a kernel driver): the logged-in desktop user gets access (uaccess),
  and the ``plugdev`` group does for headless setups.
* USB-serial boards (mesh radios, ESP32 wardrivers, PortaPack, Flipper, GPS):
  ModemManager is told to leave them alone. It otherwise probes every new serial
  port with AT commands for ~30 s, which resets or confuses these boards.
"""

from __future__ import annotations

import sys


def _usb_radios() -> list[tuple[int, int, str]]:
    from ..detect import RTLSDR_IDS
    from ..hackrf import PIDS as HACKRF_PIDS, VID as HACKRF_VID
    try:
        from ..wardrive import ar9271, mt7612u
        mt, ar = sorted(mt7612u.VID_PIDS), sorted(ar9271.VID_PIDS)
    except ImportError:            # libusb1 not installed yet: the same tables, by hand
        mt, ar = [(0x0E8D, 0x7610), (0x0E8D, 0x7612)], [(0x0CF3, 0x1006), (0x0CF3, 0x9271)]
    out = [(v, p, "RTL-SDR") for v, p in sorted(RTLSDR_IDS)]
    out += [(HACKRF_VID, p, "HackRF") for p in HACKRF_PIDS]
    out += [(v, p, "MT7612U monitor mode") for v, p in mt]
    out += [(v, p, "AR9271 monitor mode") for v, p in ar]
    return out


def _serial_boards() -> list[tuple[int, int | None, str]]:
    from ..detect import MESH_SERIAL_IDS
    from ..mayhem import MAYHEM_IDS
    from ..wardrive.boards import USB_IDS
    ids: dict[tuple[int, int | None], str] = {}
    for (v, p), name in MESH_SERIAL_IDS.items():
        ids[(v, p)] = name
    for v, p in USB_IDS:
        ids.setdefault((v, p), "wardrive board")
    for v, p in MAYHEM_IDS:
        ids[(v, p)] = "PortaPack (Mayhem)"
    ids[(0x303A, None)] = "Espressif native USB"
    ids[(0x239A, None)] = "Adafruit / nRF52 boards"
    ids[(0x1546, None)] = "u-blox GPS"
    return sorted(ids.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0))  # type: ignore[return-value]


def rules() -> str:
    lines = ["# Wardrive Uploader - generated by `python -m wdgwars_uploader.linux.udev`; installed by install.sh",
             "", "# USB radios opened from user space (libusb)"]
    # udev has no trailing comments: each rule's label goes on the line above it.
    for v, p, name in _usb_radios():
        lines.append(f"# {name}")
        lines.append(f'SUBSYSTEM=="usb", ENV{{DEVTYPE}}=="usb_device", ATTR{{idVendor}}=="{v:04x}", '
                     f'ATTR{{idProduct}}=="{p:04x}", MODE="0660", GROUP="plugdev", TAG+="uaccess"')
    lines += ["", "# USB-serial boards: keep ModemManager from probing them"]
    boards = _serial_boards()
    whole = {v for (v, p), _ in boards if p is None}
    for (v, p), name in boards:
        if p is not None and v in whole:
            continue                      # the vendor-wide rule covers it
        prod = f', ATTRS{{idProduct}}=="{p:04x}"' if p is not None else ""
        lines.append(f"# {name}")
        lines.append(f'SUBSYSTEMS=="usb", ATTRS{{idVendor}}=="{v:04x}"{prod}, ENV{{ID_MM_DEVICE_IGNORE}}="1"')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(rules())
